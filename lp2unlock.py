#!/usr/bin/env python3
"""Unlock every installed custom part in a Lost Planet 2 save.

  lp2unlock.py --game NATIVEPC SAVE OUT        (SAVE and OUT may be the same path; keep a backup)

Only the four part-unlock bitfields (save section 1, game object +0x50710..0x5078f) change,
and only for ids whose CustomParts archives exist, so nothing unloadable gets unlocked
(body set 2d has table entries but no files). DLC ids 180+ are left alone: the game recomputes
them from installed packages at boot. The SHA-1 header is regenerated by lp2save.encode.

Section sizes come from the DX9 save writer FUN_00858850; the order is header u32 @0x18 (0-3).
"""
import os, struct, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lp2save  # noqa: E402
from peva import PE  # noqa: E402

ORDERS = [[9, 3, 5, 7, 6, 2, 1, 8, 4, 0], [9, 6, 8, 7, 5, 4, 1, 2, 0, 3],
          [9, 4, 7, 5, 3, 8, 2, 0, 6, 1], [9, 2, 4, 1, 5, 3, 8, 6, 0, 7]]
SIZES = {0: 0x50, 1: 0x2CC, 2: 0x20, 3: 0x2E4, 4: 0x84, 5: 0x770, 6: 0x10, 7: 0x2F50, 9: 0}
# category -> (prefix, descriptor table VA in the DX9 exe, entries, mask offset inside section 1)
CATS = [("hd", 0x1630C68, 0x86, 0x00), ("bd", 0x1631070, 0xAD, 0x20),
        ("bk", 0x1630E80, 0x7B, 0x60), ("lg", 0x1631328, 0x7B, 0x40)]
EXE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "unpack", "LP2DX9.exe.unpacked.exe")


def section_offsets(plain, order):
    offs, pos = {}, 0
    for sec in ORDERS[order]:
        offs[sec] = pos
        if sec == 8:  # variable: u32 total size, or a lone 0 (4 bytes)
            n = struct.unpack_from("<I", plain, pos)[0]
            pos += n if n else 4
        else:
            pos += SIZES[sec]
    return offs


def installed_ids(pe, parts_dir):
    have = {f[:-4].lower() for f in os.listdir(parts_dir) if f.lower().endswith(".arc")}
    out = {}
    for pfx, tab, n, _ in CATS:
        ids = []
        for i in range(n):
            d = pe.u32(tab + 4 * i)
            setb, col, var = d & 0xFF, (d >> 8) & 0xFF, (d >> 16) & 0xFF
            s = setb if setb == 0x0F else setb | 0x20
            base = f"{pfx}{s:02x}{var:02x}"
            if base in have and (s == 0x0F or f"{base}{col:02x}" in have):
                ids.append(i)
        out[pfx] = ids
    return out


def main():
    a = sys.argv[1:]
    if len(a) != 4 or a[0] != "--game":
        raise SystemExit(__doc__)
    game, src, dst = a[1], a[2], a[3]
    raw = open(src, "rb").read()
    plain, ok = lp2save.decode(raw)
    if not ok:
        raise SystemExit("save header does not verify; refusing to edit")
    order = struct.unpack_from("<I", raw, 0x18)[0]
    sec1 = section_offsets(plain, order)[1]
    ids = installed_ids(PE(EXE), os.path.join(game, "arcXmlTmpPC", "CustomParts"))
    buf = bytearray(plain)
    for pfx, _, _, moff in CATS:
        words = list(struct.unpack_from("<8I", buf, sec1 + moff))
        before = sum(bin(w).count("1") for w in words)
        for i in ids[pfx]:
            words[i >> 5] |= 0x80000000 >> (i & 31)
        struct.pack_into("<8I", buf, sec1 + moff, *words)
        print(f"{pfx}: {before} -> {sum(bin(w).count('1') for w in words)} unlocked")
    open(dst, "wb").write(lp2save.encode(bytes(buf), raw[0x14:0x20]))
    print(f"wrote {dst} (section order {order}, part masks at plain {sec1:#x})")


if __name__ == "__main__":
    main()
